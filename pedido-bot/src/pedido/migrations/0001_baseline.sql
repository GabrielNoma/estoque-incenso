-- Baseline migration 0001: the schema of features 003 to 005, idempotent (every statement is `if not exists`),
-- so it adopts a database that already has these tables. Postgres with pgvector. `__DIMENSIONS__` is replaced by the
-- configured embedding size, which is fixed when the table `apelidos` is created.
create extension if not exists vector;
create schema if not exists pedido;

-- One-time cleanup of the tables of features 001/002 (aliases, review runs, vector memory): it only
-- runs when one of them exists.
-- BACKUP: this drops ONLY the demonstration tables of features 001/002 (no customer orders live there);
-- take a backup before applying it to a database that still holds them.
do $$
begin
    if exists (select 1 from information_schema.tables where table_schema = 'pedido'
               and table_name in ('aliases', 'runs', 'run_lines', 'memoria_linhas', 'memoria_mensagens')) then
        drop table if exists pedido.memoria_mensagens, pedido.memoria_linhas, pedido.run_lines,
                             pedido.runs, pedido.aliases cascade;
    end if;
end
$$;

create table if not exists pedido.catalog (
    id integer primary key,
    nome text not null,
    nome_normalizado text not null,
    categoria text not null,
    bloco integer not null,
    linha integer not null,
    celula_qtd text not null
);

create table if not exists pedido.pedidos (
    id bigint generated by default as identity primary key,
    telefone text not null,
    mensagem text not null,
    itens jsonb not null,
    lista text not null,
    estado text not null default 'aguardando'
        check (estado in ('aguardando', 'confirmado', 'recusado', 'substituido')),
    resposta text,
    criado_em timestamptz not null default now(),
    respondido_em timestamptz
);
alter table pedido.pedidos add column if not exists linhas jsonb not null default '[]';
create index if not exists pedidos_telefone_idx on pedido.pedidos (telefone, id desc);
-- at most one order waiting for an answer per phone number
create unique index if not exists pedidos_um_aguardando on pedido.pedidos (telefone) where estado = 'aguardando';

-- The silent nickname memory: written wordings, the product they were confirmed for, the signals.
create table if not exists pedido.apelidos (
    id bigint generated by default as identity primary key,
    texto_normalizado text not null,
    produto_id integer not null,
    embedding vector(__DIMENSIONS__),
    modelo text,
    positivos integer not null default 0,
    negativos integer not null default 0,
    status text not null default 'ativo' check (status in ('ativo', 'desativado')),
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now(),
    unique (texto_normalizado, produto_id)
);
alter table pedido.apelidos add column if not exists produto_nome text;
create index if not exists apelidos_texto_idx on pedido.apelidos (texto_normalizado);
create index if not exists apelidos_embedding_idx on pedido.apelidos using hnsw (embedding vector_cosine_ops);

-- The order-form models: every uploaded file is kept; exactly one is active.
create table if not exists pedido.modelos (
    id bigint generated by default as identity primary key,
    versao integer not null unique,
    arquivo text not null,
    conteudo bytea not null,
    produtos integer not null,
    ativo boolean not null default false,
    criado_em timestamptz not null default now()
);
create unique index if not exists modelos_um_ativo on pedido.modelos (ativo) where ativo;
alter table pedido.pedidos add column if not exists modelo_versao integer;

-- Row-level security with no policies: a hosted REST API exposes nothing; the application connects
-- as the table owner, which bypasses RLS.
alter table pedido.catalog enable row level security;
alter table pedido.pedidos enable row level security;
alter table pedido.apelidos enable row level security;
alter table pedido.modelos enable row level security;
