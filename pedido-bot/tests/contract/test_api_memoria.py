"""The memory through the HTTP app: the fake server answers chat AND embeddings."""
import logging
import time

import pytest

from fakes import InlineExecutor
from pedido import db
from pedido.llm import build_chat_model
from pedido.normalize import normalize
from pedido.web.app import FROM_ENV, create_app
from fastapi.testclient import TestClient

KEY = "chave-secreta-embed-9"
WORDING, SIMILAR = "ogun", "arruda velha"


def configure(monkeypatch, server, **extra):
    env = {"EMBED_BASE_URL": server.base_url, "EMBED_MODEL": "fake-embed", "EMBED_API_KEY": KEY,
           "EMBED_DIMENSIONS": "1024", **extra}
    for name, value in env.items():
        monkeypatch.setenv(name, value)


def chat_for(server, key="chave-chat"):
    return build_chat_model({"LLM_PROVIDER": "openai_compatible", "LLM_BASE_URL": server.base_url,
                             "LLM_MODEL": "fake-chat", "LLM_API_KEY": key})


def order(texto):
    return {"linhas": [{"texto": texto, "quantidade": 1}]}


def app_for(url, server, monkeypatch, **extra):
    configure(monkeypatch, server, **extra)
    return TestClient(create_app(database_url=url, chat_model=chat_for(server), executor=InlineExecutor()))


def send(http, phone, text):
    return http.post("/api/mensagem", json={"telefone": phone, "texto": text}).json()


def test_a_full_conversation_learns_after_two_confirmations_and_then_applies(clean_db, openai_server, monkeypatch):
    openai_server.embed_vectors = {normalize(WORDING): [1.0, 0.0], normalize(SIMILAR): [0.99, 0.1]}
    openai_server.chat_answers += [order(WORDING), order(WORDING), order(SIMILAR)]
    http = app_for(clean_db, openai_server, monkeypatch)
    for phone in ("1", "2"):  # two confirmations of the same wording for the same product
        assert send(http, phone, WORDING)["resposta"].startswith("Ogum")
        assert send(http, phone, "ok")["arquivo"]
    assert send(http, "3", SIMILAR)["resposta"] == "Ogum — 1 dz\n\nok ou não?"
    (row,) = http.app.state.store.list_apelidos()
    assert row["positivos"] == 2 and row["modelo"] == "fake-embed" and row["aplica"] is True


@pytest.mark.parametrize("problem", ["slow", "down"])
def test_a_slow_or_down_embedding_service_never_breaks_the_conversation(clean_db, openai_server, monkeypatch, problem):
    seed = {normalize(WORDING): [1.0, 0.0]}
    openai_server.embed_vectors = seed
    openai_server.chat_answers += [order(WORDING), order(WORDING), order("zzz qqq")]
    http = app_for(clean_db, openai_server, monkeypatch, EMBED_TIMEOUT_SECONDS="1")
    for phone in ("1", "2"):
        send(http, phone, WORDING)
        send(http, phone, "ok")  # a nickname with an embedding exists now
    if problem == "slow":
        openai_server.embed_delay = 3
    else:
        openai_server.embed_fail_status = 500  # only the embeddings fail; the chat model still answers
    started = time.monotonic()
    reply = send(http, "3", "zzz qqq")
    waited = time.monotonic() - started
    assert reply["resposta"].endswith("ok ou não?") and "erro" not in reply
    assert waited < 3.5  # the configured limit (1 s) plus a margin, not the server's 3 s
    done = send(http, "3", "ok")
    assert done["arquivo"] and done["resposta"] == "Pedido confirmado. Segue a planilha."


def test_without_embed_settings_the_app_behaves_as_before(clean_db, stub_chat, monkeypatch):
    for name in ("EMBED_BASE_URL", "EMBED_MODEL", "EMBED_API_KEY"):
        monkeypatch.delenv(name, raising=False)
    http = TestClient(create_app(database_url=clean_db, chat_model=stub_chat([order("ogum")]), embedder=FROM_ENV))
    assert http.app.state.memoria is None
    assert send(http, "1", "ogum")["resposta"] == "Ogum — 1 dz\n\nok ou não?"


def test_an_old_003_database_is_upgraded_at_startup_keeping_its_orders(scratch_database_url, stub_chat, monkeypatch):
    monkeypatch.setenv("MIGRATE_ON_START", "true")  # a database from before the migrations, upgraded on purpose
    url = scratch_database_url()
    with db.connect(url) as conn:
        conn.execute("create schema pedido; create table pedido.pedidos (id bigint generated by default as "
                     "identity primary key, telefone text not null, mensagem text not null, itens jsonb not null, "
                     "lista text not null, estado text not null default 'aguardando', resposta text, "
                     "criado_em timestamptz not null default now(), respondido_em timestamptz);"
                     "insert into pedido.pedidos (telefone, mensagem, itens, lista) values ('1', 'm', '[]', 'l')")
    http = TestClient(create_app(database_url=url, chat_model=stub_chat([order("ogum")]), embedder=None))
    assert len(http.app.state.store.list_pedidos()) == 1
    assert send(http, "9", "ogum")["resposta"].endswith("ok ou não?")


def test_the_embedding_key_never_leaks(clean_db, openai_server, monkeypatch, caplog):
    caplog.set_level(logging.DEBUG)
    openai_server.chat_answers += [order(WORDING)] * 2
    http = app_for(clean_db, openai_server, monkeypatch)
    bodies = [http.post("/api/mensagem", json={"telefone": "1", "texto": t}).text for t in (WORDING, "ok")]
    store = http.app.state.store
    blob = "".join(bodies) + http.get("/openapi.json").text + http.get("/").text
    blob += repr(store.list_apelidos()) + repr(store.list_pedidos()) + caplog.text
    assert KEY not in blob
    assert openai_server.requests[-1]["authorization"] in (f"Bearer {KEY}", "Bearer chave-chat")
